import '../domain/models/wheel_storage.dart';

const kJournalSeedVersion = '2';

WheelLot _lot({
  required int no,
  DateTime? received,
  String vehicle = '',
  String plate = '',
  String first = '',
  String last = '',
  String phone = '',
  String vin = '',
  String size = '',
  String size2 = '',
  String rim = '',
  String brand = '',
  bool rims = false,
  StorageCargo? cargo,
  String notes = '',
  TireSeason season = TireSeason.winter,
}) {
  return WheelLot(
    id: 'journal-${no.toString().padLeft(2, '0')}',
    journalNo: no,
    receivedAt: received,
    dateUncertain: received == null,
    vehicle: vehicle,
    plate: plate,
    firstName: first,
    lastName: last,
    phone: phone,
    vin: vin,
    sizePrimary: size,
    sizeSecondary: size2,
    rimDiameter: rim,
    tireBrand: brand,
    cargo: cargo ?? StorageCargoX.fromLegacy(withRims: rims),
    season: season,
    notes: notes,
  );
}

